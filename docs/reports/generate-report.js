function table(headers, rows, widths, opts = {}) {
  const cw = widths.map((f) => Math.round(W * f));
  cw[cw.length - 1] = W - cw.slice(0, -1).reduce((a, b) => a + b, 0);
  const cell = (text, i, o = {}) => new TableCell({
    width: { size: cw[i], type: WidthType.DXA },
    shading: o.bg ? { type: ShadingType.CLEAR, fill: o.bg, color: "auto" } : undefined,
    margins: { top: 70, bottom: 70, left: 110, right: 110 },
    children: [new Paragraph({
      alignment: o.align,
      spacing: { before: 0, after: 0, line: 260 },
      children: [t(String(text), { size: o.size || 17, bold: o.bold, color: o.color })]
    })]
  });
  return new Table({
    columnWidths: cw,
    width: { size: W, type: WidthType.DXA },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 6, color: "C9D6CE" },
      bottom: { style: BorderStyle.SINGLE, size: 6, color: "C9D6CE" },
      left: { style: BorderStyle.SINGLE, size: 6, color: "C9D6CE" },
      right: { style: BorderStyle.SINGLE, size: 6, color: "C9D6CE" },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 4, color: "DCE5DF" },
      insideVertical: { style: BorderStyle.SINGLE, size: 4, color: "DCE5DF" }
    },
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((hh, i) => cell(hh, i, { bg: HEADBG, bold: true, align: AlignmentType.CENTER, color: GREEN }))
      }),
      ...rows.map((r, ri) => new TableRow({
        children: r.map((c, i) => cell(c, i, {
          bg: ri % 2 === 1 ? ALTBG : undefined,
          align: i === 0 ? undefined : (opts.numCols && opts.numCols.includes(i) ? AlignmentType.RIGHT : undefined),
          bold: opts.boldFirst && i === 0
        }))
      }))
    ]
  });
}
